#!/bin/bash
# new_ep.sh N: create the P3 episode folder R/epN: aud/ st/, fonts link, the default phone image, wrapper scripts
# (prep, align, stills, sfx, run_all -> the kit), and a placeholder scenes_epN.js (one scene per segment scene) if none exists.
# Env: P3_ROOT (default: the folder that holds kit/). Never touches R/plan.
set -euo pipefail
[ $# -eq 1 ] || { echo "usage: new_ep.sh N"; exit 2; }
K=$(cd "$(dirname "$0")" && pwd); R=$(cd "${P3_ROOT:-$K/..}" && pwd); S4=$(cd "$K/../.." && pwd)
N=$1; NN=$(printf %02d $N); D=$R/ep$N
mkdir -p $D/aud $D/st
ln -sfn $S4/ep1/fonts $D/fonts
[ -e $D/oneapp_mind.png ] || cp $S4/ep1/oneapp_mind.png $D/
w() { printf '#!/bin/bash\n# generated by kit/new_ep.sh: %s\n%s\n' "$2" "$3" > $D/$1; chmod +x $D/$1; }
w prep.sh "full prep of episode $N (TTS cached, align, timeline, page, fills, page check)" "P3_ROOT=$R exec python3 $K/prep_p3.py $N"
w align.sh "re-run only the word alignment (debug): writes align_check.json" "cd $D && exec python3 $K/align.py $D/segments.json $D/aud $D/align_check.json"
w stills.sh "stills: ./stills.sh 12.5 40 ... -> st/s_<t>.jpg" "NODE_PATH=\$(npm root -g) exec node $K/stills.js $D/ep${N}b.html $D/st \"\$@\""
w sfx.sh "rebuild sfx.wav from tl.json" "exec python3 -I $K/sfx.py $D"
w run_all.sh "render + mix -> the mp4 named in meta.json" "exec bash $K/run_all.sh $D"
if [ ! -e $D/scenes_ep$N.js ]; then
  python3 - "$R/plan/ep${NN}_segments.json" "$D/scenes_ep$N.js" <<'PY'
import json, os, sys
segp, out = sys.argv[1:3]
scenes = list(dict.fromkeys(s["scene"] for s in json.load(open(segp)))) if os.path.exists(segp) else ["hook"]
cols = [("#4cc9f0", "#7209b7"), ("#ffd166", "#06d6a0"), ("#a2d2ff", "#cdb4db"), ("#ffe8d6", "#ddbea9"), ("#caf0f8", "#90e0ef"), ("#d8f3dc", "#b7e4c7")]
L = ["// Scene code for this episode: one S.<scene> per segment \"scene\" value (see kit/README.md). Placeholders below.", ""]
for i, sc in enumerate(scenes):
    c1, c2 = cols[i % len(cols)]
    L.append(f'// ---- {sc.upper()}')
    L.append(f'S.{sc} = (() => {{ const s = scene("{sc}", "{c1}", "{c2}");')
    L.append(f'  s.title = chip(s.stage, "TODO: {sc}", "#7209b7", {{fs: 46}});')
    if sc == "mindmap":
        L.append('  const P = mmPhone(s.stage); s.phone = P.g; s.shot = P.shot;')
        L.append('  s.run = t => { const a = w => C("habit2", w); op(s.title, 1); popAt(s.title, 760, 300, t, SC.mindmap.t0);')
        L.append('    const ph = ramp(t, a("save"), a("save") + .6); op(s.phone, ph); tf(s.phone, `translate(${lerp(1650, 1320, ph)} 520) rotate(${lerp(12, -4, ph)})`); }; return s; })();')
    else:
        L.append(f'  s.run = t => {{ op(s.title, 1); popAt(s.title, 760, 480, t, SC.{sc}.t0); }}; return s; }})();')
    L.append("")
open(out, "w").write("\n".join(L))
print("wrote placeholder", out, "with scenes:", ", ".join(scenes))
PY
fi
echo "ep$N ready: $D  (next: write $R/plan/ep${NN}.json + scenes_ep$N.js, then $D/prep.sh)"
